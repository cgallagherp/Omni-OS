// Master playbook generation: Claude when configured (and allowed by the company), the
// rule-based extractor otherwise. Both outputs go through the same mapping, grounding and
// validation, so whatever is stored is a valid, source-checked draft.
import { analyseWithRules, similarity, titleTokens } from "./analyse-rules";
import { callStructured, claudeConfigured, genPlaybook, PLAYBOOK_SYSTEM, type ClaudeClient, type GenPlaybook } from "./claude";
import { groundPlaybook, passagesForPrompt, type SourceChunk } from "./grounding";
import { omit, playbookContent, timingLabel, uniqueKey, type Citation, type PlaybookContent } from "./schema";

/** Passages beyond this are not sent; the note says so (never silently truncated). */
export const MAX_PROMPT_CHARS = 600_000;

export interface PlaybookDraft {
  content: PlaybookContent;
  name: string;
  applies_when: string;
  acquisition_types: string[];
  generator: "claude" | "rules";
  model: string | null;
  note: string;
}

export async function generatePlaybook(chunks: SourceChunk[], opts: { useClaude: boolean; client?: ClaudeClient; name?: string } = { useClaude: true }): Promise<PlaybookDraft> {
  if (!chunks.length) throw new Error("No readable passages in the selected documents");
  if (opts.useClaude && (opts.client || claudeConfigured())) {
    let used = chunks;
    let size = 0;
    const kept: SourceChunk[] = [];
    for (const c of chunks) {
      size += c.text.length + 80;
      if (size > MAX_PROMPT_CHARS) break;
      kept.push(c);
    }
    used = kept;
    const { text, ids } = passagesForPrompt(used);
    const r = await callStructured(genPlaybook, PLAYBOOK_SYSTEM, `Selected company documents:\n${text}\n\nBuild the playbook.`, { client: opts.client, effort: "high" });
    const content = groundPlaybook(fromGenerated(r.data, ids, used), used);
    const skipped = chunks.length - used.length;
    return {
      content,
      name: opts.name || r.data.name || "Integration playbook",
      applies_when: r.data.applies_when,
      acquisition_types: r.data.acquisition_type_names.slice(0, 10),
      generator: "claude",
      model: r.model,
      note: `Generated by ${r.model} from ${content.stats?.sources} documents (${used.length} passages). ${content.stats?.citations_rejected ?? 0} citations could not be verified and were removed; ${content.stats?.demoted ?? 0} items without verifiable evidence are shown as recommendations.${skipped ? ` ${skipped} passages exceeded the size limit and were not analysed — select fewer documents to include them.` : ""}`,
    };
  }
  const raw = playbookContent.parse(analyseWithRules(chunks));
  const content = groundPlaybook(raw, chunks);
  return {
    content,
    name: opts.name || "Integration playbook",
    applies_when: content.acquisition_types.map((t) => `${t.name}: ${t.when}`).join(" ") || "Acquisitions integrated into the company.",
    acquisition_types: content.acquisition_types.map((t) => t.name).slice(0, 10),
    generator: "rules",
    model: null,
    note: `Built by the rule-based extractor because no AI provider is configured${opts.useClaude ? "" : " for this company"}. It reads document structure (sections, lists, tables, timing, owners) and is less thorough than AI analysis: review every workstream.`,
  };
}

/** Model output → storage schema: keys, passage ids → chunk ids, dependency titles → keys. */
export function fromGenerated(g: GenPlaybook, ids: Map<string, string>, chunks: SourceChunk[]): PlaybookContent {
  const chunkById = new Map(chunks.map((c) => [c.id, c]));
  const cites = (cs: Array<{ passage: string; quote: string }>): Citation[] =>
    cs.flatMap((c) => {
      const id = ids.get(c.passage.trim().replace(/^\[|\]$/g, ""));
      const ch = id ? chunkById.get(id) : undefined;
      return ch ? [{ source_id: ch.source_id, chunk_id: ch.id, quote: c.quote.slice(0, 600), source_title: ch.source_title }] : [];
    }).slice(0, 12);
  const keys = new Set<string>();
  const actKeys = new Set<string>();
  const workstreams = g.workstreams.slice(0, 20).map((w) => ({
    key: uniqueKey(w.name, keys),
    name: w.name.slice(0, 120),
    objective: w.objective.slice(0, 1000),
    accountable_function: w.accountable_function.slice(0, 120),
    basis: w.basis,
    rationale: w.rationale.slice(0, 1500),
    citations: cites(w.citations),
    decision: (w.basis === "recommended" ? "pending" : "accepted") as "pending" | "accepted",
    applies_to: [] as string[],
    activities: w.activities.slice(0, 60).map((a) => {
      const t = { anchor: a.timing_anchor, start_offset_days: clamp(a.start_offset_days), due_offset_days: clamp(a.due_offset_days), label: "" };
      t.label = (a.timing_label || timingLabel(t)).slice(0, 80);
      return {
        key: uniqueKey(a.title, actKeys),
        title: a.title.slice(0, 300),
        description: a.description.slice(0, 2000),
        accountable_function: a.accountable_function.slice(0, 120),
        timing: t,
        milestone: a.milestone,
        critical: a.critical,
        completion_criteria: a.completion_criteria.slice(0, 1000),
        evidence_required: a.evidence_required.slice(0, 1000),
        approval_required: a.approval_required ? a.approval_required.slice(0, 200) : null,
        depends_on: [] as string[],
        dependsTitles: a.depends_on_titles,
        basis: a.basis,
        rationale: a.rationale.slice(0, 1500),
        citations: cites(a.citations),
        decision: (a.basis === "recommended" ? "pending" : "accepted") as "pending" | "accepted",
        human_only: false,
        human_only_reason: null,
        applies_to: a.applies_to.slice(0, 10).map((x) => x.slice(0, 80)),
      };
    }),
  }));
  const all = workstreams.flatMap((w) => w.activities);
  for (const a of all) {
    for (const t of a.dependsTitles) {
      const exact = all.find((b) => b !== a && b.title.toLowerCase() === t.toLowerCase());
      const tk = titleTokens(t);
      const near = exact ?? all.filter((b) => b !== a).map((b) => ({ b, s: similarity(titleTokens(b.title), tk) })).filter((x) => x.s >= 0.8).sort((x, y) => y.s - x.s)[0]?.b;
      if (near && !a.depends_on.includes(near.key)) a.depends_on.push(near.key);
    }
  }
  const k = (p: string) => uniqueKey(p, keys);
  const out = {
    summary: g.summary.slice(0, 3000),
    philosophy: g.philosophy.slice(0, 20).map((p) => ({ text: p.text.slice(0, 1500), basis: p.basis, citations: cites(p.citations) })),
    acquisition_types: g.acquisition_types.slice(0, 12).map((t) => ({ name: t.name.slice(0, 120), when: t.when.slice(0, 1000), basis: t.basis, citations: cites(t.citations) })),
    workstreams: workstreams.map((w) => ({ ...w, activities: w.activities.map((a) => omit(a, ["dependsTitles"])) })),
    risks: g.risks.slice(0, 40).map((r) => ({ key: k(`risk_${r.description.slice(0, 30)}`), description: r.description.slice(0, 1000), escalation_trigger: r.escalation_trigger.slice(0, 500), escalate_to: r.escalate_to.slice(0, 120), basis: r.basis, citations: cites(r.citations) })),
    kpis: g.kpis.slice(0, 30).map((x) => ({ key: k(`kpi_${x.name.slice(0, 30)}`), name: x.name.slice(0, 300), target: x.target.slice(0, 200), basis: x.basis, citations: cites(x.citations) })),
    synergy_rules: g.synergy_rules.slice(0, 20).map((s) => ({ text: s.text.slice(0, 1500), basis: s.basis, citations: cites(s.citations) })),
    conflicts: g.conflicts.filter((c) => c.positions.length >= 2).slice(0, 30).map((c) => ({ key: k(`conflict_${c.topic.slice(0, 30)}`), topic: c.topic.slice(0, 300), positions: c.positions.slice(0, 6).map((p) => ({ text: p.text.slice(0, 1000), citations: cites(p.citations).slice(0, 6) })), resolution: "" })),
    gaps: g.gaps.slice(0, 40).map((x) => ({ key: k(`gap_${x.question.slice(0, 30)}`), question: x.question.slice(0, 500), context: x.context.slice(0, 1000), answer: "" })),
    lessons: g.lessons.slice(0, 40).map((l) => ({ key: k(`lesson_${l.text.slice(0, 30)}`), text: l.text.slice(0, 1000), citations: cites(l.citations), applied_in: null })),
  };
  return playbookContent.parse(out);
}

const clamp = (n: number) => Math.max(-365, Math.min(1095, Math.round(n)));
